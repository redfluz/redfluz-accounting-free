declare(strict_types=1);

namespace App\Http\Requests\System\User;

use App\Enums\FileAction;
use App\Enums\FileResources;
use Illuminate\Validation\Rule;

/**
 * The fields a user is created from.
 *
 * A new user takes only a name and email. The password is set from configuration
 * and the role is assigned by the controller from the default role. The rules
 * live here rather than in the controller so that the controller can be handed a
 * request that has already been checked.
 */
class StoreUserRequest extends UserRequest
{
    /**
     * Who may create a user.
     *
     * The permission lives here rather than in the controller, so that the request
     * says everything about who may send it and what it must contain. Laravel
     * asks this before the controller runs, so a request that is not permitted
     * never reaches the action it was meant to guard.
     */
    public function authorize(): bool
    {
        return $this->allows(FileResources::USERS, FileAction::ADD);
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'name' => ['required', 'string', 'max:255'],
            'email' => [
                'required',
                'string',
                'email',
                'max:255',
                Rule::unique('users', 'email')->withoutTrashed(),
            ],
        ];
    }
}
