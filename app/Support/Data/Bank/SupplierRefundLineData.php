declare(strict_types=1);

namespace App\Support\Data\Bank;

use App\Models\Bank\Refund\SupplierRefundLine;
use Carbon\CarbonImmutable;
use Carbon\CarbonInterface;
use Spatie\LaravelData\Attributes\MapName;
use Spatie\LaravelData\Data;

/**
 * One leg of a supplier_refunds: one side of the figure, against one account.
 *
 * A line carries either a debit or a credit, never both. That is what lets the two
 * sides add to the same figure without every row holding an amount in both
 * directions, and it is why a document split across several accounts is
 * representable at all: a two account payment is three lines, not two.
 *
 * The account codes are kept alongside the ids rather than resolved on read, so a
 * document printed years later shows the accounts that were correct when it was
 * raised even if the chart of accounts has been renamed since.
 *
 * @param  numeric-string  $amount
 */
class SupplierRefundLineData extends Data
{
    public function __construct(
        #[MapName('id')]
        public string $id,

        #[MapName('refund_id')]
        public string $refundId,

        #[MapName('amount')]
        public string $amount,

        #[MapName('description')]
        public ?string $description,

        #[MapName('created_at')]
        public ?CarbonImmutable $createdAt,

        #[MapName('updated_at')]
        public ?CarbonImmutable $updatedAt,

        #[MapName('deleted_at')]
        public ?CarbonImmutable $deletedAt,
    ) {}

    /**
     * The same moment, as the type this object holds.
     *
     * A model hands back whatever Carbon its cast produced; this object holds one
     * concrete type so that a form and a model produce the same thing. The value
     * is the same either way, and only its class differs.
     */
    private static function moment(?CarbonInterface $value): ?CarbonImmutable
    {
        return $value === null ? null : CarbonImmutable::instance($value);
    }

    /**
     * Build from the model, which has already cast its own columns.
     *
     * Not Data::from($model->getAttributes()): that reads the raw row, where a
     * date is the string the database stores rather than the date object the model
     * holds, and the two are written in different formats. Taking the model's
     * attributes instead means the cast is what is mapped.
     */
    public static function fromModel(SupplierRefundLine $model): self
    {
        return new self(
            id: $model->id,
            refundId: $model->refund_id,
            amount: $model->amount,
            description: $model->description,
            createdAt: self::moment($model->created_at),
            updatedAt: self::moment($model->updated_at),
            deletedAt: self::moment($model->deleted_at),
        );
    }

    /**
     * The row as the supplier_refund_lines table wants it.
     *
     * @return array<string, mixed>
     */
    public function toRow(): array
    {
        /** @var array<string, mixed> $row */
        $row = [
            ...$this->toArray(),
            'created_at' => $this->createdAt?->format('Y-m-d H:i:s'),
            'updated_at' => $this->updatedAt?->format('Y-m-d H:i:s'),
            'deleted_at' => $this->deletedAt?->format('Y-m-d H:i:s'),
        ];

        return $row;
    }
}
