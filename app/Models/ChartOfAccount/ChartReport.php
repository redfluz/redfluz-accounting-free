namespace App\Models\ChartOfAccount;

use Carbon\CarbonInterface;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Spatie\Activitylog\Models\Activity;
use Spatie\Activitylog\Models\Concerns\HasActivity;
use Spatie\Activitylog\Support\LogOptions;

/**
 * @mixin Builder<ChartReport>
 *
 * @property string $id
 * @property string|null $code
 * @property string $name
 * @property string $slug
 * @property string $calculation_basis
 * @property bool $is_default
 * @property CarbonInterface|null $created_at
 * @property CarbonInterface|null $updated_at
 * @property CarbonInterface|null $deleted_at
 * @property-read Collection<int, ChartReportDetail> $details
 *
 * @noinspection PhpUnused
 *
 * @property-read Collection<int, Activity> $activities
 * @property-read Collection<int, Activity> $activitiesAsCauser
 * @property-read Collection<int, Activity> $activitiesAsSubject
 */
#[Table('chart_reports', key: 'id')]
#[Fillable([
    'code',
    'name',
    'slug',
    'calculation_basis',
    'is_default',
])]
class ChartReport extends Model
{
    use HasActivity, HasUuids, SoftDeletes;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'code' => 'string',
            'name' => 'string',
            'slug' => 'string',
            'calculation_basis' => 'string',
            'is_default' => 'boolean',
        ];
    }

    /**
     * Define a one-to-many relationship.
     * Define a one-to-many relationship with the ordered report rows.
     *
     * @return HasMany<ChartReportDetail, $this>
     */
    public function details(): HasMany
    {
        return $this->hasMany(ChartReportDetail::class, 'chart_report_id')
            ->orderBy('line');
    }

    /**
     * Get the options for logging activity using Spatie Activitylog.
     *
     * @return LogOptions Returns configured log options.
     */
    public function getActivitylogOptions(): LogOptions
    {
        return LogOptions::defaults()
            ->logFillable()
            ->logOnlyDirty();
    }
}
